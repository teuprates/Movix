require('dotenv').config();
const path = require('path');
const express = require('express');
const helmet = require('helmet');
const cors = require('cors');
const rateLimit = require('express-rate-limit');
const errorHandler = require('./middlewares/error-handler');
const app = express();
app.disable('x-powered-by');
app.use(helmet({ contentSecurityPolicy: false }));
app.use(cors({ origin: process.env.ALLOWED_ORIGIN || 'http://localhost:3000' }));
app.use(express.json({ limit: '100kb' }));
app.use('/api/', rateLimit({ windowMs: 15 * 60 * 1000, limit: 180, standardHeaders: true, legacyHeaders: false }));
app.use('/api/health', require('./routes/health'));
app.use('/api/auth', require('./routes/auth'));
app.use('/api', (req, res) => res.status(404).json({ error: 'Rota não encontrada.', code: 'NOT_FOUND' }));
app.use(express.static(path.resolve(__dirname, '../../frontend')));
app.get('*', (req, res) => res.sendFile(path.resolve(__dirname, '../../frontend/index.html')));
app.use(errorHandler);
const port = Number(process.env.PORT) || 3000;
if (require.main === module) app.listen(port, () => console.log(`MOVIX disponível em http://localhost:${port}`));
module.exports = app;
